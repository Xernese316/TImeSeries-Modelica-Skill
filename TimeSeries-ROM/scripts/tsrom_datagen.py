"""Generate training data from the HEAVY Modelica model with OpenModelica (any model, driven by a JSON spec).

Each run = the heavy model extended with modifiers: random piecewise-constant tables (APRBS excitation),
random parameters, random/cold initial states. One extra run reproduces the original model unchanged
(this becomes the held-out test run).

CLI:
  python tsrom_datagen.py --spec work/datagen.json            # writes DataGen.mo + gen_data.mos and runs omc
  python tsrom_datagen.py --spec work/datagen.json --no-run   # only writes the files

Spec (see references/omc-data-generation.md):
{
  "model": "Modelica.Thermal.HeatTransfer.Examples.Motor",
  "out_dir": "work/omc_data", "stop_time": 7200, "intervals": 1440, "n_runs": 30, "seed": 0,
  "tables": [ {"component": "lossTable", "time_step": 5,
               "columns": [ {"lo": 0, "hi": 1200, "hold_min": 60, "hold_max": 900},
                            {"lo": 0, "hi": 900,  "hold_min": 120, "hold_max": 1800} ] } ],
  "parameters":   [ {"name": "TAmb", "lo": 273.15, "hi": 318.15} ],
  "start_values": [ {"name": "winding.T", "lo_offset": 0, "hi_offset": 80, "relative_to": "TAmb", "cold_fraction": 0.33},
                    {"name": "core.T",    "lo_offset": 0, "hi_offset": 60, "relative_to": "TAmb", "cold_fraction": 0.33} ],
  "extra_declarations": ["Real TAmbSig = TAmb;"],
  "variable_filter": "time|winding.T|core.T|lossTable.y.1.|lossTable.y.2.|TAmbSig",
  "include_original": true
}
"""
import argparse, json, os, subprocess, sys, time
import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))


def aprbs_rows(rng, t_end, cols, step):
    """Change points for each column (random levels, random hold times on a grid of `step`), merged."""
    per = []
    for c in cols:
        t, rows = 0.0, []
        while t < t_end:
            rows.append((t, rng.uniform(c["lo"], c["hi"])))
            h = rng.uniform(c["hold_min"], c["hold_max"]); t += max(step, step * round(h / step))
        per.append(rows)
    ts = sorted({r[0] for rows in per for r in rows})
    val = lambda rows, t: [v for tt, v in rows if tt <= t + 1e-9][-1]
    M = [[t] + [val(rows, t) for rows in per] for t in ts]
    M.append([t_end + max(step, 1.0)] + M[-1][1:])        # cover the full horizon (no periodic wrap-around)
    return M


def mat(M):
    return "[" + "; ".join(",".join(f"{v:.6g}" for v in row) for row in M) + "]"


def build(spec):
    rng = np.random.default_rng(spec.get("seed", 0))
    model, n = spec["model"], int(spec["n_runs"])
    T_end = float(spec["stop_time"])
    mo = ['package DataGen "Heavy-model data generation harness (generated by tsrom_datagen.py)"']
    runs, meta = [], []
    for i in range(n):
        mods, record = [], {}
        params = {}
        for p in spec.get("parameters", []):
            v = rng.uniform(p["lo"], p["hi"]); params[p["name"]] = v; record[p["name"]] = v
            mods.append(f'{p["name"]}={v:.6g}')
        for tb in spec.get("tables", []):
            smooth = tb.get("smoothness", "ConstantSegments")
            M = aprbs_rows(rng, T_end, tb["columns"], float(tb.get("time_step", T_end / 1000)))
            mods.append(f'{tb["component"]}(table={mat(M)}, smoothness=Modelica.Blocks.Types.Smoothness.{smooth}, '
                        f'extrapolation=Modelica.Blocks.Types.Extrapolation.HoldLastPoint)')
        cold = rng.random() < max([s.get("cold_fraction", 0) for s in spec.get("start_values", [])] or [0])
        for s in spec.get("start_values", []):
            base = params.get(s["relative_to"], s.get("relative_value", 0.0)) if s.get("relative_to") else 0.0
            if cold and s.get("cold_fraction", 0) > 0:
                v = base
            elif "relative_to" in s:
                v = base + rng.uniform(s.get("lo_offset", 0), s.get("hi_offset", 0))
            else:
                v = rng.uniform(s["lo"], s["hi"])
            record[s["name"] + ".start"] = v
            path = s["name"].split(".")             # winding.T -> winding(T(start=...))
            mod = f"start={v:.6g}"
            for part in reversed(path):
                mod = f"{part}({mod})"
            mods.append(mod)
        name = f"run_{i+1:03d}"
        decl = "".join(f"    {d}\n" for d in spec.get("extra_declarations", []))
        mo.append(f"  model {name}\n    extends {model}({', '.join(mods)});\n{decl}  end {name};")
        runs.append(name); meta.append(dict(run=name, cold_start=bool(cold), **record))
    if spec.get("include_original", True):
        decl = "".join(f"    {d}\n" for d in spec.get("extra_declarations", []))
        mo.append(f"  model original\n    extends {model};\n{decl}  end original;"); runs.append("original")
        meta.append(dict(run="original", note="unmodified heavy model - use as test run"))
    mo.append("end DataGen;")
    flt = spec.get("variable_filter", ".*")
    mos = ['loadModel(Modelica, {"4.0.0"}); getErrorString();']
    for f in spec.get("load_files", []):          # the user's own heavy-model library, if not in MSL
        mos.append(f'loadFile("{f}"); getErrorString();')
    mos.append('loadFile("DataGen.mo"); getErrorString();')
    for r in runs:
        mos.append(f'simulate(DataGen.{r}, stopTime={T_end:g}, numberOfIntervals={int(spec["intervals"])}, '
                   f'outputFormat="csv", fileNamePrefix="{r}", variableFilter="{flt}"); getErrorString();')
    return "\n".join(mo) + "\n", "\n".join(mos) + "\n", meta


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--spec", required=True); ap.add_argument("--no-run", action="store_true")
    a = ap.parse_args()
    spec = json.load(open(a.spec))
    base = os.path.dirname(os.path.abspath(a.spec))
    out = os.path.join(base, spec.get("out_dir", "omc_data"))   # relative paths are relative to the spec file
    os.makedirs(out, exist_ok=True)
    mo, mos, meta = build(spec)
    open(os.path.join(out, "DataGen.mo"), "w", newline="\n").write(mo)
    open(os.path.join(out, "gen_data.mos"), "w", newline="\n").write(mos)
    json.dump(meta, open(os.path.join(out, "runs.json"), "w"), indent=1)
    print(f"wrote {out}/DataGen.mo and gen_data.mos ({len(meta)} runs)")
    if a.no_run:
        return
    from tsrom_verify import find_omc
    omc = find_omc()
    if not omc:
        print("omc not found: run   omc gen_data.mos   inside", out); sys.exit(1)
    t0 = time.time()
    p = subprocess.run([omc, "gen_data.mos"], cwd=out, capture_output=True, text=True, timeout=spec.get("timeout", 7200))
    open(os.path.join(out, "gen_data.log"), "w").write(p.stdout + p.stderr)
    made = [r["run"] for r in meta if os.path.exists(os.path.join(out, f'{r["run"]}_res.csv'))]
    print(f"omc finished in {time.time()-t0:.0f}s: {len(made)}/{len(meta)} result files")
    if len(made) < len(meta):
        print("Some runs failed - read gen_data.log (look for 'Error')."); sys.exit(2)


if __name__ == "__main__":
    main()
